import assert from 'node:assert/strict';
import {WHEEL_PRIZES,claimDailyWheel,dailyWheelReward,wheelPrize,wheelCollection,dateCollectionSummary,wheelRewardId} from '../src/daily-wheel.js';
import {DATE_ITEMS,cleanDateCollection,mergeDateCollection} from '../supabase/functions/english-for-two-sync/date-collection.js';
import {balanceOf,dayKey} from '../src/learning.js';
import {backupRecords,mergeBackup} from '../src/private-backup.js';
import {mergeCoupleSnapshot} from '../src/couple-sync.js';
import {dailyAdventure} from '../src/arcade.js';
const now=Date.parse('2026-10-13T09:00:00Z'),oldIds=['star','lightning','crystal','clover','crown'];
const empty=()=>({earned:{old:{amount:30,at:1}},spent:{gift:{cost:5,status:'approved',at:2}},goals:{}});
function give(wallet,prizeId,index) {
  const at=now-index*86400000,day=dayKey(at),prize=wheelPrize({prizeId});
  return {...wallet,earned:{...wallet.earned,[wheelRewardId(at)]:{kind:'daily-wheel',version:oldIds.includes(prizeId)?1:2,day,prizeId,amount:prize.amount,at}}};
}
assert.equal(WHEEL_PRIZES.length,8);assert.equal(WHEEL_PRIZES.filter(p=>p.amount).length,3);
assert.deepEqual(WHEEL_PRIZES.filter(p=>!p.amount).map(p=>p.id),DATE_ITEMS);
assert.equal(wheelCollection(empty()).nextProgress,0);assert.equal(wheelCollection(empty()).completed,0);
for(let i=0;i<5;i++)assert.equal(wheelPrize({prizeId:oldIds[i]}).id,DATE_ITEMS[i]);
const legacyCrystal=give(empty(),'crystal',0),before=JSON.stringify(legacyCrystal);
assert.equal(wheelCollection(legacyCrystal).items.find(p=>p.id==='ticket').count,1);
assert.equal(wheelCollection(legacyCrystal).nextProgress,1);
assert.equal(claimDailyWheel(legacyCrystal,'changed-profile',now).duplicate,true);
assert.equal(dailyWheelReward(legacyCrystal,now).prizeId,'crystal');
assert.equal(JSON.stringify(legacyCrystal),before,'reading the collection must not rewrite the ledger');
assert.equal(balanceOf(legacyCrystal),25);
let repeats=empty();for(let i=0;i<7;i++)repeats=give(repeats,i%2?'star':'bouquet',i);
assert.equal(wheelCollection(repeats).nextProgress,1);assert.equal(wheelCollection(repeats).completed,0);
assert.equal(wheelCollection(repeats).items[0].count,7,'duplicates accumulate but cannot substitute other items');
let full=empty();for(let i=0;i<5;i++)full=give(full,oldIds[i],i);
assert.equal(wheelCollection(full).completed,1);assert.equal(wheelCollection(full).nextProgress,0);
assert.equal(balanceOf(full),25,'a date prize is not cash and never debits the wallet');
full=give(full,'bouquet',5);assert.equal(wheelCollection(full).completed,1);assert.equal(wheelCollection(full).nextProgress,1);
for(let i=1;i<5;i++)full=give(full,DATE_ITEMS[i],5+i);
assert.equal(wheelCollection(full).completed,2);assert.equal(wheelCollection(full).nextProgress,0);
assert.equal(balanceOf(give(full,'double',10)),27);
const state={level:'B1',progress:{},stats:{lessons:{},byDay:{},legacy:{}},wallet:full};
const records=backupRecords(state),restored=mergeBackup({...state,wallet:empty()},records);
const twice=mergeBackup(restored,records);
assert.deepEqual(wheelCollection(twice.wallet),wheelCollection(full));assert.equal(balanceOf(twice.wallet),25);
// Same ledger key from old/new devices counts once, whichever backup is later.
const aliasUpdate={...legacyCrystal,earned:{...legacyCrystal.earned,[wheelRewardId(now)]:{...dailyWheelReward(legacyCrystal,now),prizeId:'ticket',version:2,at:now+1}}};
const aliasMerged=mergeBackup({...state,wallet:legacyCrystal},backupRecords({...state,wallet:aliasUpdate}));
assert.equal(wheelCollection(aliasMerged.wallet).items.find(p=>p.id==='ticket').count,1);
const summary=dateCollectionSummary(full);
assert.deepEqual(summary,{version:1,counts:{bouquet:2,coffee:2,ticket:2,bag:2,keys:2},completed:2});
assert.equal(cleanDateCollection({version:99,counts:summary.counts}),null);
const dirty=cleanDateCollection({version:1,completed:999,counts:{bouquet:-1,coffee:Infinity,ticket:'5',bag:1.5,keys:10000000,unknown:99}});
assert.deepEqual(dirty,{version:1,counts:{bouquet:0,coffee:0,ticket:0,bag:0,keys:10000},completed:0});
assert.deepEqual(mergeDateCollection(summary,null),summary);assert.deepEqual(mergeDateCollection(null,summary),summary);
assert.deepEqual(mergeDateCollection(summary,{version:1,counts:{bouquet:1}}),summary);
assert.equal(mergeDateCollection({version:1,counts:{bouquet:1,coffee:1}},{version:1,counts:{ticket:1,bag:1,keys:1}}).completed,1);
const snapshot={paired:true,partner:{displayName:'Anna',dateCollection:summary}};
const coupled=mergeCoupleSnapshot(empty(),snapshot);
assert.equal(coupled.partner.dateCollection.completed,2);
assert.deepEqual(mergeCoupleSnapshot(coupled,{paired:true,partner:{displayName:'Anna'}}).partner.dateCollection,summary);
assert.equal(mergeCoupleSnapshot(coupled,{paired:false}).partner,null);
assert.equal(balanceOf(coupled),25);assert.deepEqual(coupled.earned,empty().earned);
const focus=dailyAdventure('Artur',now);
for(let i=0;i<30;i++)claimDailyWheel(empty(),'qa-'+i,now);
assert.deepEqual(dailyAdventure('Artur',now),focus,'prizes cannot choose a lesson or affect the automatic mix');
console.log('✓ date collection: 5 distinct items, duplicates for later sets, legacy aliases, no cash debit, idempotent backups, bounded partner metadata and independent lessons');
